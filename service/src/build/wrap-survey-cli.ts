import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { REPO_ROOT, SUBTITLE_SAFE_WIDTH } from '@framopia/core';
import { readEditPlan } from '../editplan/io.js';
import { runMeasureSurvey } from './drive.js';
import { chooseBreak, type BreakCandidate } from './wrap.js';

/**
 * Free and local: drives the running After Effects, calls no API and writes no
 * plan. Every figure in the output comes back from AE's own `sourceRectAtTime`.
 */
const FOOTAGE_DIR = path.join(REPO_ROOT, 'my files', 'test videos');
const AEP_PATH = path.join(REPO_ROOT, 'templates', 'library.aep');
const OUT_PATH = path.join(REPO_ROOT, 'benchmarks', 'RESULTS-block7-wrapping.md');

interface Card {
  id: string;
  kind: 'subtitle' | 'keyword';
  templateId: string;
  candidate: BreakCandidate;
}

interface Fit {
  wrapped: boolean;
  overflows: boolean;
  reason: string | null;
  oneLineWidth: number;
  wrappedWidth: number | null;
  lineWidths: number[] | null;
  lineRects: { top: number; left: number; width: number; height: number }[] | null;
  oneLineTop: number;
  wrappedTop: number | null;
  lineCount: number;
}

const reels: { reel: string; cards: Card[] }[] = [];
const templateIds = new Set<string>();

for (const file of readdirSync(FOOTAGE_DIR).filter((f) => f.endsWith('.editplan.json')).sort()) {
  const plan = await readEditPlan(path.join(FOOTAGE_DIR, file));
  const wordText = new Map(plan.transcript.words.map((w) => [w.id, w.text]));
  const superseded = new Set(
    plan.subtitles.groups.filter((g) => g.supersededBy != null).map((g) => g.id),
  );
  const cards: Card[] = [];
  for (const g of plan.subtitles.groups) {
    if (superseded.has(g.id) || g.templateId === null) continue;
    cards.push({
      id: g.id,
      kind: 'subtitle',
      templateId: g.templateId,
      candidate: chooseBreak(g.wordIds.map((id) => wordText.get(id) ?? '').join(' ')),
    });
    templateIds.add(g.templateId);
  }
  for (const k of plan.keywords.items) {
    if (k.templateId === null) continue;
    cards.push({ id: k.id, kind: 'keyword', templateId: k.templateId, candidate: chooseBreak(k.text) });
    templateIds.add(k.templateId);
  }
  if (cards.length > 0) reels.push({ reel: file.replace('.editplan.json', ''), cards });
}

const startedAt = Date.now();
const result = runMeasureSurvey({
  templatesAepPath: AEP_PATH,
  safeWidth: SUBTITLE_SAFE_WIDTH,
  templateIds: [...templateIds].sort(),
  probeText: 'dernière génération',
  reels,
});
const wallS = (Date.now() - startedAt) / 1000;

if (!result.ok) {
  console.error(`wrap-survey: ${result.stage}: ${result.message}`);
  process.exit(1);
}

interface SurveyReel { reel: string; cards: { id: string; kind: string; templateId: string; text: string; fit: Fit }[] }
interface Independence {
  templateId: string;
  atZero: { top: number; left: number; width: number; height: number };
  atSample: { top: number; left: number; width: number; height: number };
  positionAtZero: number[];
  positionAtSample: number[];
}
const survey = result as unknown as { reels: SurveyReel[]; independence: Independence[] };

const totalCards = survey.reels.reduce((n, r) => n + r.cards.length, 0);
const f1 = (v: number): string => v.toFixed(1);

const L: string[] = [];
L.push('# Block 7 — how wide the cards actually are');
L.push('');
L.push('Generated by `npm run wrap:survey`. Every width here is reported by After Effects');
L.push('from `sourceRectAtTime` on the populated text layer — nothing is computed from font');
L.push('metrics, and nothing is hand-typed.');
L.push('');
L.push(`Bound: \`SUBTITLE_SAFE_WIDTH\` = **${SUBTITLE_SAFE_WIDTH}** px inside a 2160-wide comp.`);
L.push(`Cards measured: **${totalCards}** across ${survey.reels.length} reels. Wall clock **${f1(wallS)} s**.`);
L.push('');
L.push('## Is the source rect independent of the layer transform?');
L.push('');
L.push('`TXT_MAIN` has a keyframed Position, so if the source rect followed the transform the');
L.push('two samples below would differ. Measured rather than assumed.');
L.push('');
L.push('| template | position at 0 | position at sample | rect at 0 (w x h @ top) | rect at sample |');
L.push('|---|---|---|---|---|');
for (const i of survey.independence) {
  L.push(
    `| ${i.templateId} | [${i.positionAtZero.join(', ')}] | [${i.positionAtSample.join(', ')}] | ` +
      `${f1(i.atZero.width)} x ${f1(i.atZero.height)} @ ${f1(i.atZero.top)} | ` +
      `${f1(i.atSample.width)} x ${f1(i.atSample.height)} @ ${f1(i.atSample.top)} |`,
  );
}
const independent = survey.independence.every(
  (i) => i.atZero.width === i.atSample.width && i.atZero.top === i.atSample.top,
);
L.push('');
L.push(independent
  ? '**Identical at both times on every template, while Position differs** — the source rect is the layer\'s own bounds before its transforms, so the sample time cannot bias a width.'
  : '**They differ.** The source rect is not transform-independent on this build of After Effects, which makes the sample time load-bearing; every figure below is at the sample time and no other.');
L.push('');
L.push('## Per reel');
L.push('');
L.push('| reel | cards | one line | wrapped | single word overflowing | widest card | widest width |');
L.push('|---|---:|---:|---:|---:|---|---:|');
const allOverflow: { reel: string; card: SurveyReel['cards'][number] }[] = [];
const allWrapped: { reel: string; card: SurveyReel['cards'][number] }[] = [];
for (const r of survey.reels) {
  const wrapped = r.cards.filter((c) => c.fit.wrapped);
  const over = r.cards.filter((c) => c.fit.overflows);
  const widest = r.cards.reduce((a, b) => (b.fit.oneLineWidth > a.fit.oneLineWidth ? b : a));
  L.push(
    `| ${r.reel} | ${r.cards.length} | ${r.cards.length - wrapped.length} | ${wrapped.length} | ` +
      `${over.filter((c) => !c.fit.wrapped).length} | ${widest.id} "${widest.text}" | ${f1(widest.fit.oneLineWidth)} |`,
  );
  for (const c of over) allOverflow.push({ reel: r.reel, card: c });
  for (const c of wrapped) allWrapped.push({ reel: r.reel, card: c });
}
const wrappedTotal = allWrapped.length;
L.push(
  `| **all** | ${totalCards} | ${totalCards - wrappedTotal} | **${wrappedTotal}** | ` +
    `${allOverflow.filter((o) => !o.card.fit.wrapped).length} | — | — |`,
);
L.push('');
L.push('## Every card that wrapped');
L.push('');
if (allWrapped.length === 0) {
  L.push('None.');
} else {
  L.push('| reel | id | kind | text | one line | wrapped | line 1 | line 2 |');
  L.push('|---|---|---|---|---:|---:|---:|---:|');
  for (const { reel, card } of allWrapped) {
    const w = card.fit.lineWidths ?? [];
    L.push(
      `| ${reel} | ${card.id} | ${card.kind} | ${card.text} | ${f1(card.fit.oneLineWidth)} | ` +
        `${f1(card.fit.wrappedWidth ?? 0)} | ${f1(w[0] ?? 0)} | ${f1(w[1] ?? 0)} |`,
    );
  }
}
L.push('');
L.push('## Cards the ruling does not cover');
L.push('');
L.push('A single word wider than the bound has no break point. It is emitted whole and flagged;');
L.push('nothing is shrunk and nothing is broken mid-word. **This is the conversation\'s to settle.**');
L.push('');
const single = allOverflow.filter((o) => !o.card.fit.wrapped);
if (single.length === 0) {
  L.push('None: every card that exceeded the bound had a space to break at.');
} else {
  L.push('| reel | id | kind | text | measured width | over by |');
  L.push('|---|---|---|---|---:|---:|');
  for (const { reel, card } of single) {
    L.push(
      `| ${reel} | ${card.id} | ${card.kind} | ${card.text} | ${f1(card.fit.oneLineWidth)} | ` +
        `${f1(card.fit.oneLineWidth - SUBTITLE_SAFE_WIDTH)} |`,
    );
  }
}
const stillOver = allOverflow.filter((o) => o.card.fit.wrapped);
L.push('');
L.push('## Cards still over the bound after breaking');
L.push('');
L.push(stillOver.length === 0
  ? 'None: every card that wrapped fits on both lines.'
  : stillOver.map((o) => `- ${o.reel} ${o.card.id} "${o.card.text}": ${o.card.fit.reason}`).join('\n'));
L.push('');
L.push('## Does wrapping move the first line?');
L.push('');
L.push('The ruling is that the second line renders **below** the first, so a wrapped card must');
L.push('keep its first baseline where a one-line card puts it.');
L.push('');
L.push('**The test is not the obvious one.** The source rect\'s `top` is the distance from the');
L.push('anchor to the top of the *ink*, so it moves whenever the break changes which glyphs land');
L.push('on line one — a card losing its only capital to line two reads as "the line moved" when');
L.push('nothing moved at all. The honest comparison is the wrapped rect\'s top against **line one');
L.push('measured on its own**: equal means the two-line block puts line one exactly where that');
L.push('line alone would sit, so the baseline is untouched.');
L.push('');
if (allWrapped.length === 0) {
  L.push('No card wrapped, so there is nothing to compare.');
} else {
  const moved = allWrapped.filter(
    (o) => o.card.fit.wrappedTop !== (o.card.fit.lineRects?.[0]?.top ?? null),
  );
  const naive = allWrapped.filter((o) => o.card.fit.oneLineTop !== o.card.fit.wrappedTop);
  L.push('| reel | id | line 1 alone, top | wrapped block, top | first line moved |');
  L.push('|---|---|---:|---:|---|');
  for (const { reel, card } of allWrapped) {
    const lineTop = card.fit.lineRects?.[0]?.top ?? 0;
    const same = card.fit.wrappedTop === lineTop;
    L.push(`| ${reel} | ${card.id} | ${f1(lineTop)} | ${f1(card.fit.wrappedTop ?? 0)} | ${same ? 'no' : '**YES**'} |`);
  }
  L.push('');
  L.push(moved.length === 0
    ? `**The first line does not move on any of the ${allWrapped.length} wrapped cards.** The approved baseline at y 2480.4 survives wrapping, and \`EXTRA_LINES_RENDER_BELOW\` is confirmed against real cards rather than reasoned about.`
    : `**${moved.length} of ${allWrapped.length} wrapped cards moved their first line.** That contradicts the ruling and the approved position.`);
  L.push('');
  L.push(`For the record, the naive comparison — one-line rect top against wrapped rect top — flags **${naive.length}** of ${allWrapped.length}. Every one of those is a card whose tallest glyph moved to line two; none of them is a card whose baseline moved.`);
}
L.push('');
writeFileSync(OUT_PATH, `${L.join('\n')}\n`, 'utf8');
console.log(`wrote ${path.relative(REPO_ROOT, OUT_PATH)}`);
console.log(
  `${totalCards} cards in ${f1(wallS)}s: ${wrappedTotal} wrapped, ` +
    `${allOverflow.filter((o) => !o.card.fit.wrapped).length} single-word overflow, ` +
    `${stillOver.length} still over after breaking; transform-independent: ${independent}`,
);
